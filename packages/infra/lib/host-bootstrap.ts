import { createHash } from "node:crypto";
import {
  CLOUDWATCH_AGENT_CONFIG,
  CLOUDWATCH_AGENT_CONFIG_PATH,
  CONTAINER_HEALTH_SCRIPT,
  CONTAINER_HEALTH_SCRIPT_PATH,
  CONTAINER_HEALTH_SERVICE,
  CONTAINER_HEALTH_SERVICE_NAME,
  CONTAINER_HEALTH_TIMER,
  CONTAINER_HEALTH_TIMER_NAME,
} from "./host-monitoring.js";

const DOCKER_COMPOSE_VERSION = "v5.7.1";
const DOCKER_COMPOSE_ARM64_SHA256 =
  "f2f49f903240895fa764c0dca3a14548b754ad9426f6b609ccaf55ec5a3aa2a5";
const SHELL_LINE_CONTINUATION = String.fromCharCode(92);

export const HOST_BOOTSTRAP_SCRIPT = [
  "#!/usr/bin/env bash",
  "set -Eeuo pipefail",
  "",
  "trap 'echo \"Host bootstrap failed at line ${LINENO}.\" >&2' ERR",
  "",
  'DATABASE_VOLUME_ID="{{ DatabaseVolumeId }}"',
  'DATABASE_VOLUME_SERIAL="${DATABASE_VOLUME_ID//-/}"',
  'DATABASE_MOUNT_PATH="/srv/finhand/postgres"',
  'COMPOSE_VERSION="' + DOCKER_COMPOSE_VERSION + '"',
  'COMPOSE_SHA256="' + DOCKER_COMPOSE_ARM64_SHA256 + '"',
  'COMPOSE_PLUGIN_PATH="/usr/local/lib/docker/cli-plugins/docker-compose"',
  'SWAP_FILE="/swapfile"',
  "",
  "if [[ $(id -u) -ne 0 ]]; then",
  '  echo "Host bootstrap must run as root." >&2',
  "  exit 1",
  "fi",
  "",
  "install_host_packages() {",
  "  dnf install -y amazon-cloudwatch-agent docker e2fsprogs jq util-linux-core",
  "  systemctl enable --now docker",
  "}",
  "",
  "install_docker_compose() (",
  '  local installed_version=""',
  '  if [[ -x "$COMPOSE_PLUGIN_PATH" ]]; then',
  '    installed_version=$(docker compose version --short 2>/dev/null || true)',
  "  fi",
  "",
  '  if [[ "${installed_version#v}" == "${COMPOSE_VERSION#v}" ]]; then',
  "    return",
  "  fi",
  "",
  '  local download_path checksum_path',
  '  download_path=$(mktemp)',
  '  checksum_path=$(mktemp)',
  '  trap \'rm -f "$download_path" "$checksum_path"\' EXIT',
  "",
  "  curl --fail --location --silent --show-error --retry 3 " +
    SHELL_LINE_CONTINUATION,
  '    "https://github.com/docker/compose/releases/download/${COMPOSE_VERSION}/docker-compose-linux-aarch64" ' +
    SHELL_LINE_CONTINUATION,
  '    --output "$download_path"',
  '  printf \'%s  %s\\n\' "$COMPOSE_SHA256" "$download_path" > "$checksum_path"',
  '  sha256sum --check "$checksum_path"',
  "",
  '  install -d -m 0755 "$(dirname "$COMPOSE_PLUGIN_PATH")"',
  '  install -m 0755 "$download_path" "$COMPOSE_PLUGIN_PATH"',
  '  docker compose version',
  ")",
  "",
  "configure_docker_logging() (",
  '  local config_path="/etc/docker/daemon.json"',
  '  local current_path desired_path',
  '  current_path=$(mktemp)',
  '  desired_path=$(mktemp)',
  '  trap \'rm -f "$current_path" "$desired_path"\' EXIT',
  "",
  '  if [[ -f "$config_path" ]]; then',
  '    jq empty "$config_path"',
  '    cp "$config_path" "$current_path"',
  "  else",
  '    printf \'{}\\n\' > "$current_path"',
  "  fi",
  "",
  "  jq --sort-keys '",
  '    . + {"log-driver": "json-file"}',
  '      + {"log-opts": ((.["log-opts"] // {})',
  '          + {"max-size": "10m", "max-file": "3"})}',
  "  ' \"$current_path\" > \"$desired_path\"",
  "",
  '  if [[ ! -f "$config_path" ]] || ! cmp --silent "$config_path" "$desired_path"; then',
  '    install -d -m 0755 "$(dirname "$config_path")"',
  '    install -m 0644 "$desired_path" "$config_path"',
  "    systemctl restart docker",
  "  fi",
  ")",
  "",
  "find_database_device() {",
  '  local device=""',
  '  local by_id_path="/dev/disk/by-id/nvme-Amazon_Elastic_Block_Store_${DATABASE_VOLUME_SERIAL}"',
  "",
  "  for _ in $(seq 1 30); do",
  '    if [[ -e "$by_id_path" ]]; then',
  '      device=$(readlink --canonicalize "$by_id_path")',
  "    else",
  "      device=$(lsblk --nodeps --noheadings --output NAME,SERIAL,TYPE | " +
    SHELL_LINE_CONTINUATION,
  '        awk -v serial="$DATABASE_VOLUME_SERIAL" \'$2 == serial && $3 == "disk" { print "/dev/" $1; exit }\')',
  "    fi",
  "",
  '    if [[ -n "$device" && -b "$device" ]]; then',
  '      printf \'%s\\n\' "$device"',
  "      return",
  "    fi",
  "",
  "    sleep 2",
  "  done",
  "",
  '  echo "Could not find attached EBS volume $DATABASE_VOLUME_ID." >&2',
  "  return 1",
  "}",
  "",
  "mount_database_volume() {",
  '  local device filesystem_type filesystem_uuid mounted_uuid signatures',
  '  device=$(find_database_device)',
  "",
  '  filesystem_type=$(blkid --match-tag TYPE --output value "$device" 2>/dev/null || true)',
  '  if [[ -z "$filesystem_type" ]]; then',
  '    signatures=$(wipefs --no-act --noheadings --output TYPE "$device" | xargs || true)',
  '    if [[ -n "$signatures" ]]; then',
  '      echo "Refusing to format $device because existing signatures were detected: $signatures" >&2',
  "      return 1",
  "    fi",
  "",
  '    echo "No filesystem exists on $device; creating a new ext4 filesystem."',
  '    mkfs.ext4 -L finhand-postgres "$device"',
  '    filesystem_type="ext4"',
  "  fi",
  "",
  '  if [[ "$filesystem_type" != "ext4" ]]; then',
  '    echo "Refusing to mount unsupported $filesystem_type filesystem on $device." >&2',
  "    return 1",
  "  fi",
  "",
  '  filesystem_uuid=$(blkid --match-tag UUID --output value "$device")',
  '  if [[ -z "$filesystem_uuid" ]]; then',
  '    echo "Could not read the filesystem UUID from $device." >&2',
  "    return 1",
  "  fi",
  "",
  '  install -d -m 0755 "$DATABASE_MOUNT_PATH"',
  '  if mountpoint --quiet "$DATABASE_MOUNT_PATH"; then',
  '    mounted_uuid=$(findmnt --noheadings --output UUID --target "$DATABASE_MOUNT_PATH")',
  '    if [[ "$mounted_uuid" != "$filesystem_uuid" ]]; then',
  '      echo "$DATABASE_MOUNT_PATH is mounted from an unexpected filesystem." >&2',
  "      return 1",
  "    fi",
  "  fi",
  "",
  '  local fstab_path="/etc/fstab" fstab_temp',
  '  fstab_temp=$(mktemp)',
  '  awk -v mount_path="$DATABASE_MOUNT_PATH" \'$2 != mount_path { print }\' "$fstab_path" > "$fstab_temp"',
  '  printf \'UUID=%s %s ext4 defaults,nofail 0 2\\n\' "$filesystem_uuid" "$DATABASE_MOUNT_PATH" >> "$fstab_temp"',
  '  install -m 0644 "$fstab_temp" "$fstab_path"',
  '  rm -f "$fstab_temp"',
  "",
  '  if ! mountpoint --quiet "$DATABASE_MOUNT_PATH"; then',
  '    mount "$DATABASE_MOUNT_PATH"',
  "  fi",
  '  chown root:root "$DATABASE_MOUNT_PATH"',
  '  chmod 0755 "$DATABASE_MOUNT_PATH"',
  "}",
  "",
  "configure_swap() {",
  '  local swap_type=""',
  '  if [[ -e "$SWAP_FILE" ]]; then',
  '    swap_type=$(blkid --probe --match-tag TYPE --output value "$SWAP_FILE" 2>/dev/null || true)',
  '    if [[ "$swap_type" != "swap" ]]; then',
  '      echo "Refusing to replace existing non-swap path $SWAP_FILE." >&2',
  "      return 1",
  "    fi",
  "  else",
  '    fallocate --length 1G "$SWAP_FILE"',
  '    chmod 0600 "$SWAP_FILE"',
  '    mkswap "$SWAP_FILE"',
  "  fi",
  "",
  '  chmod 0600 "$SWAP_FILE"',
  '  if ! swapon --show=NAME --noheadings | grep --fixed-strings --line-regexp --quiet "$SWAP_FILE"; then',
  '    swapon "$SWAP_FILE"',
  "  fi",
  "",
  '  if ! grep --extended-regexp --quiet "^[[:space:]]*$SWAP_FILE[[:space:]]" /etc/fstab; then',
  '    printf \'%s none swap defaults 0 0\\n\' "$SWAP_FILE" >> /etc/fstab',
  "  fi",
  "",
  "  printf 'vm.swappiness = 10\\n' > /etc/sysctl.d/99-finhand-swap.conf",
  "  sysctl --load /etc/sysctl.d/99-finhand-swap.conf",
  "}",
  "",
  "create_application_directories() {",
  "  install -d -o root -g root -m 0755 /opt/finhand",
  "  install -d -o root -g root -m 0755 /opt/finhand/bin",
  "  install -d -o root -g root -m 0700 /opt/finhand/config",
  "  install -d -o root -g root -m 0755 /opt/finhand/releases",
  "  install -d -o root -g root -m 0750 /opt/finhand/runtime",
  "}",
  "",
  "configure_cloudwatch_agent() (",
  `  local config_path="${CLOUDWATCH_AGENT_CONFIG_PATH}"`,
  "  local config_temp",
  "  config_temp=$(mktemp)",
  "  trap 'rm -f \"$config_temp\"' EXIT",
  "",
  "  cat > \"$config_temp\" <<'FINHAND_CLOUDWATCH_AGENT_CONFIG'",
  CLOUDWATCH_AGENT_CONFIG,
  "FINHAND_CLOUDWATCH_AGENT_CONFIG",
  '  install -d -m 0755 "$(dirname "$config_path")"',
  '  install -m 0644 "$config_temp" "$config_path"',
  "",
  "  /opt/aws/amazon-cloudwatch-agent/bin/amazon-cloudwatch-agent-ctl \\",
  "    -a fetch-config \\",
  "    -m ec2 \\",
  "    -s \\",
  '    -c "file:$config_path"',
  ")",
  "",
  "configure_container_health_timer() (",
  "  local script_temp service_temp timer_temp",
  "  script_temp=$(mktemp)",
  "  service_temp=$(mktemp)",
  "  timer_temp=$(mktemp)",
  "  trap 'rm -f \"$script_temp\" \"$service_temp\" \"$timer_temp\"' EXIT",
  "",
  "  cat > \"$script_temp\" <<'FINHAND_CONTAINER_HEALTH_SCRIPT'",
  CONTAINER_HEALTH_SCRIPT.trimEnd(),
  "FINHAND_CONTAINER_HEALTH_SCRIPT",
  "  cat > \"$service_temp\" <<'FINHAND_CONTAINER_HEALTH_SERVICE'",
  CONTAINER_HEALTH_SERVICE.trimEnd(),
  "FINHAND_CONTAINER_HEALTH_SERVICE",
  "  cat > \"$timer_temp\" <<'FINHAND_CONTAINER_HEALTH_TIMER'",
  CONTAINER_HEALTH_TIMER.trimEnd(),
  "FINHAND_CONTAINER_HEALTH_TIMER",
  "",
  `  install -m 0755 "$script_temp" "${CONTAINER_HEALTH_SCRIPT_PATH}"`,
  `  install -m 0644 "$service_temp" "/etc/systemd/system/${CONTAINER_HEALTH_SERVICE_NAME}"`,
  `  install -m 0644 "$timer_temp" "/etc/systemd/system/${CONTAINER_HEALTH_TIMER_NAME}"`,
  "  systemctl daemon-reload",
  `  systemctl enable --now "${CONTAINER_HEALTH_TIMER_NAME}"`,
  ")",
  "",
  "install_host_packages",
  "install_docker_compose",
  "configure_docker_logging",
  "mount_database_volume",
  "configure_swap",
  "create_application_directories",
  "configure_cloudwatch_agent",
  "configure_container_health_timer",
  "",
  'echo "FinHand host bootstrap revision {{ BootstrapRevision }} completed successfully."',
].join("\n");

export const HOST_BOOTSTRAP_REVISION = createHash("sha256")
  .update(HOST_BOOTSTRAP_SCRIPT)
  .digest("hex")
  .slice(0, 16);

export function createHostBootstrapDocumentContent(): Record<string, unknown> {
  return {
    schemaVersion: "2.2",
    description:
      "Prepare the FinHand production host without starting application services.",
    parameters: {
      DatabaseVolumeId: {
        type: "String",
        description: "Retained EBS volume that stores PostgreSQL data.",
        allowedPattern: "^vol-[0-9a-f]+$",
      },
      BootstrapRevision: {
        type: "String",
        description:
          "Version-controlled value that causes State Manager to reapply changes.",
      },
    },
    mainSteps: [
      {
        action: "aws:runShellScript",
        name: "bootstrapHost",
        inputs: {
          timeoutSeconds: "900",
          runCommand: [HOST_BOOTSTRAP_SCRIPT],
        },
      },
    ],
  };
}
