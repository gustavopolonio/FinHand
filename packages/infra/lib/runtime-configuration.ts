interface RuntimeConfigurationScriptOptions {
  accountId: string;
  region: string;
  uploadsBucketName: string;
}

const PARAMETER_ROOT = "/finhand/production";
const CONFIGURATION_DIRECTORY = "/opt/finhand/config";
const DATABASE_DATA_DIRECTORY = "/srv/finhand/postgres";

export function createRuntimeConfigurationScript({
  accountId,
  region,
  uploadsBucketName,
}: RuntimeConfigurationScriptOptions): string {
  const registry = `${accountId}.dkr.ecr.${region}.amazonaws.com`;
  const webRepository = `${registry}/finhand-prod-web-ecr`;
  const apiRepository = `${registry}/finhand-prod-api-ecr`;

  return [
    "#!/usr/bin/env bash",
    "set -Eeuo pipefail",
    "",
    "trap 'echo \"Runtime configuration rendering failed at line ${LINENO}.\" >&2' ERR",
    "",
    `PARAMETER_ROOT="${PARAMETER_ROOT}"`,
    `CONFIGURATION_DIRECTORY="${CONFIGURATION_DIRECTORY}"`,
    `DATABASE_DATA_DIRECTORY="${DATABASE_DATA_DIRECTORY}"`,
    `AWS_REGION="${region}"`,
    `UPLOADS_BUCKET="${uploadsBucketName}"`,
    `WEB_REPOSITORY="${webRepository}"`,
    `API_REPOSITORY="${apiRepository}"`,
    "",
    "if [[ $(id -u) -ne 0 ]]; then",
    '  echo "Runtime configuration rendering must run as root." >&2',
    "  exit 1",
    "fi",
    "",
    "umask 077",
    'install -d -o root -g root -m 0700 "$CONFIGURATION_DIRECTORY"',
    'temporary_directory=$(mktemp -d "$CONFIGURATION_DIRECTORY/.runtime-config.XXXXXX")',
    'trap \'rm -rf "$temporary_directory"\' EXIT',
    'parameters_file="$temporary_directory/parameters.json"',
    "",
    'aws ssm get-parameters-by-path --path "$PARAMETER_ROOT" --recursive --with-decryption --region "$AWS_REGION" --output json > "$parameters_file"',
    "",
    "get_parameter() {",
    '  local relative_name="$1" expected_type="$2" full_name value',
    '  full_name="${PARAMETER_ROOT}/${relative_name}"',
    "",
    "  value=$(jq --exit-status --raw-output --arg name \"$full_name\" --arg type \"$expected_type\" '.Parameters | map(select(.Name == $name and .Type == $type)) | if length == 1 then .[0].Value else empty end' \"$parameters_file\") || {",
    '      echo "Missing Parameter Store value or unexpected type: $full_name ($expected_type required)" >&2',
    "      return 1",
    "    }",
    "",
    '  if [[ -z "$value" ]]; then',
    '    echo "Parameter Store value must not be empty: $full_name" >&2',
    "    return 1",
    "  fi",
    "",
    "  printf '%s' \"$value\"",
    "}",
    "",
    "validate_environment_value() {",
    '  local name="$1" value="$2"',
    "",
    `  if [[ "$value" == *$'\\n'* || "$value" == *$'\\r'* || "$value" == *"'"* ]]; then`,
    '    echo "$name contains characters that cannot be written safely to an environment file." >&2',
    "    return 1",
    "  fi",
    "}",
    "",
    "validate_domain() {",
    '  local name="$1" value="$2" label',
    "  local -a labels",
    "",
    '  if (( ${#value} > 253 )) || [[ "$value" != *.* ]] || [[ "$value" == *".."* ]]; then',
    '    echo "$name must be a lowercase fully qualified domain name." >&2',
    "    return 1",
    "  fi",
    "",
    '  IFS="." read -r -a labels <<< "$value"',
    '  for label in "${labels[@]}"; do',
    '    if (( ${#label} > 63 )) || [[ ! "$label" =~ ^[a-z0-9]([a-z0-9-]*[a-z0-9])?$ ]]; then',
    '      echo "$name contains an invalid DNS label." >&2',
    "      return 1",
    "    fi",
    "  done",
    "}",
    "",
    "validate_image_reference() {",
    '  local name="$1" value="$2" repository="$3" tag',
    "",
    '  if [[ "$value" != "${repository}:"* ]]; then',
    '    echo "$name must reference the expected production ECR repository." >&2',
    "    return 1",
    "  fi",
    "",
    '  tag="${value#"${repository}:"}"',
    '  if [[ ! "$tag" =~ ^[0-9a-f]{40}$ ]]; then',
    '    echo "$name must use a full Git commit SHA tag." >&2',
    "    return 1",
    "  fi",
    "}",
    "",
    "write_environment_value() {",
    '  local file="$1" name="$2" value="$3"',
    "",
    "  validate_environment_value \"$name\" \"$value\"",
    `  printf "%s='%s'\\n" "$name" "$value" >> "$file"`,
    "}",
    "",
    'web_image=$(get_parameter "deployment/web-image" "String")',
    'api_image=$(get_parameter "deployment/api-image" "String")',
    'web_domain=$(get_parameter "deployment/web-domain" "String")',
    'api_domain=$(get_parameter "deployment/api-domain" "String")',
    'acme_email=$(get_parameter "deployment/acme-email" "String")',
    'database_user=$(get_parameter "database/user" "String")',
    'database_password=$(get_parameter "database/password" "SecureString")',
    'database_name=$(get_parameter "database/name" "String")',
    'log_level=$(get_parameter "application/log-level" "String")',
    'better_auth_secret=$(get_parameter "application/better-auth-secret" "SecureString")',
    'google_client_id=$(get_parameter "application/google-client-id" "String")',
    'google_client_secret=$(get_parameter "application/google-client-secret" "SecureString")',
    'openai_api_key=$(get_parameter "application/openai-api-key" "SecureString")',
    'openai_document_model=$(get_parameter "application/openai-document-model" "String")',
    "",
    'validate_image_reference "deployment/web-image" "$web_image" "$WEB_REPOSITORY"',
    'validate_image_reference "deployment/api-image" "$api_image" "$API_REPOSITORY"',
    'if [[ "${web_image##*:}" != "${api_image##*:}" ]]; then',
    '  echo "The web and API images must use the same Git commit SHA tag." >&2',
    "  exit 1",
    "fi",
    'validate_domain "deployment/web-domain" "$web_domain"',
    'validate_domain "deployment/api-domain" "$api_domain"',
    'if [[ "$web_domain" == "$api_domain" ]]; then',
    '  echo "The web and API domains must be different." >&2',
    "  exit 1",
    "fi",
    'if [[ ! "$acme_email" =~ ^[^@[:space:]]+@[^@[:space:]]+\\.[^@[:space:]]+$ ]]; then',
    '  echo "deployment/acme-email must be a valid email address." >&2',
    "  exit 1",
    "fi",
    'if [[ ! "$database_user" =~ ^[a-z][a-z0-9_]*$ ]]; then',
    '  echo "database/user must be a lowercase PostgreSQL identifier." >&2',
    "  exit 1",
    "fi",
    'if [[ ! "$database_name" =~ ^[a-z][a-z0-9_]*$ ]]; then',
    '  echo "database/name must be a lowercase PostgreSQL identifier." >&2',
    "  exit 1",
    "fi",
    'if [[ ! "$database_password" =~ ^[A-Za-z0-9._~-]{32,128}$ ]]; then',
    '  echo "database/password must contain 32-128 URL-safe characters." >&2',
    "  exit 1",
    "fi",
    'if (( ${#better_auth_secret} < 32 )); then',
    '  echo "application/better-auth-secret must contain at least 32 characters." >&2',
    "  exit 1",
    "fi",
    'case "$log_level" in',
    "  trace|debug|info|warn|error|fatal|silent) ;;",
    "  *) echo \"application/log-level is invalid.\" >&2; exit 1 ;;",
    "esac",
    "",
    'database_url="postgresql://${database_user}:${database_password}@postgres:5432/${database_name}"',
    'better_auth_url="https://${api_domain}"',
    'web_url="https://${web_domain}"',
    "",
    'deployment_file="$temporary_directory/deployment.env"',
    'api_file="$temporary_directory/api.env"',
    'worker_file="$temporary_directory/worker.env"',
    'migration_file="$temporary_directory/migration.env"',
    'postgres_file="$temporary_directory/postgres.env"',
    "",
    'write_environment_value "$deployment_file" "FINHAND_WEB_IMAGE" "$web_image"',
    'write_environment_value "$deployment_file" "FINHAND_API_IMAGE" "$api_image"',
    'write_environment_value "$deployment_file" "WEB_DOMAIN" "$web_domain"',
    'write_environment_value "$deployment_file" "API_DOMAIN" "$api_domain"',
    'write_environment_value "$deployment_file" "ACME_EMAIL" "$acme_email"',
    `write_environment_value "$deployment_file" "FINHAND_CONFIG_DIR" "${CONFIGURATION_DIRECTORY}"`,
    `write_environment_value "$deployment_file" "POSTGRES_DATA_DIR" "${DATABASE_DATA_DIRECTORY}"`,
    "",
    'write_environment_value "$api_file" "DATABASE_URL" "$database_url"',
    'write_environment_value "$api_file" "LOG_LEVEL" "$log_level"',
    'write_environment_value "$api_file" "BETTER_AUTH_SECRET" "$better_auth_secret"',
    'write_environment_value "$api_file" "BETTER_AUTH_URL" "$better_auth_url"',
    'write_environment_value "$api_file" "GOOGLE_CLIENT_ID" "$google_client_id"',
    'write_environment_value "$api_file" "GOOGLE_CLIENT_SECRET" "$google_client_secret"',
    'write_environment_value "$api_file" "WEB_URL" "$web_url"',
    'write_environment_value "$api_file" "AWS_REGION" "$AWS_REGION"',
    'write_environment_value "$api_file" "S3_UPLOAD_BUCKET" "$UPLOADS_BUCKET"',
    "",
    'write_environment_value "$worker_file" "DATABASE_URL" "$database_url"',
    'write_environment_value "$worker_file" "LOG_LEVEL" "$log_level"',
    'write_environment_value "$worker_file" "AWS_REGION" "$AWS_REGION"',
    'write_environment_value "$worker_file" "S3_UPLOAD_BUCKET" "$UPLOADS_BUCKET"',
    'write_environment_value "$worker_file" "OPENAI_API_KEY" "$openai_api_key"',
    'write_environment_value "$worker_file" "OPENAI_DOCUMENT_MODEL" "$openai_document_model"',
    "",
    'write_environment_value "$migration_file" "DATABASE_URL" "$database_url"',
    "",
    'write_environment_value "$postgres_file" "POSTGRES_USER" "$database_user"',
    'write_environment_value "$postgres_file" "POSTGRES_PASSWORD" "$database_password"',
    'write_environment_value "$postgres_file" "POSTGRES_DB" "$database_name"',
    "",
    "for file in deployment.env api.env worker.env migration.env postgres.env; do",
    '  install -o root -g root -m 0600 "$temporary_directory/$file" "$CONFIGURATION_DIRECTORY/$file"',
    "done",
    "",
    'echo "FinHand runtime configuration files updated successfully."',
  ].join("\n");
}

export function createRuntimeConfigurationDocumentContent(
  options: RuntimeConfigurationScriptOptions,
): Record<string, unknown> {
  return {
    schemaVersion: "2.2",
    description:
      "Render protected FinHand production environment files from Parameter Store.",
    mainSteps: [
      {
        action: "aws:runShellScript",
        name: "renderRuntimeConfiguration",
        inputs: {
          timeoutSeconds: "180",
          runCommand: [createRuntimeConfigurationScript(options)],
        },
      },
    ],
  };
}

export const runtimeParameterRoot = PARAMETER_ROOT;
